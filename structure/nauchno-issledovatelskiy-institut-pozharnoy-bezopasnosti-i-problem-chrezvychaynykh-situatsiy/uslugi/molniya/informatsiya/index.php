<p>
	 К сведению покупателей! Обращаем Ваше внимание, что устройство оконечное объектовое системы передачи извещений о чрезвычайных ситуациях «Молния», выпускаемое по ТУ BY 101114857.098-2023, не комплектуется аккумуляторной батареей.&nbsp;Работа устройства оконечного объектового «Молния» предусмотрена от резервного источника питания -аккумуляторная батарея с параметрами 6В, емкость 1,3Ач, которая устанавливается в корпусе прибора и крепится с помощью двухстороннего скотча.<br>
