<h1>Специальная защитная одежда пожарных-спасателей</h1>
<p style="text-align: justify;">
	 Разработка средств индивидуальной защиты, экипировки и пожарно-технического вооружения спасателей – одна из основных задач деятельности института.&nbsp;&nbsp;
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 Боевая одежда является основным средством индивидуальной защиты пожарного-спасателя. В настоящее время институтом разработана новая модификация боевой одежды пожарного-спасателя, значительную роль в обеспечении безопасности в которой играет материал верха. Термоогнестойкий материал верха обладает высокими теплофизическими и физико-механическими свойствами. Он сохраняет свои свойства даже после длительного воздействия тепла и открытого пламени. Облегченный пакет материалов обеспечивает баланс защиты и комфорта при проведении работ. Модернизированная конструкция способствует высокому уровню эргономики.
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 На сегодняшний день наши спасатели полностью обеспечены одеждой и экипировкой отечественного производства. У них имеются обувь, боевая одежда, перчатки, подшлемники, шлемы, спасательные пояса и многое другое. Для изготовления экипировки институт сотрудничает с концернами и предприятиями Беларуси. С их помощью получается эффективный продукт высокого качества, который ценится, в том числе и за рубежом.
</p>
