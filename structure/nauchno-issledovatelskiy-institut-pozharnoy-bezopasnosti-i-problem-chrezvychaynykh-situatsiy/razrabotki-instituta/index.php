<h1>Пожарная аварийно-спасательная техника</h1>
<p style="text-align: justify;">
	 Институт активно принимает участие в разработке пожарной аварийно-спасательной техники, выпускаемой в Республике Беларусь. Спасатели являются как одними из основных заказчиков, так и конструкторов и идейных вдохновителей современной техники для служб быстрого реагирования и спасения. Среди машин, разработанных при поддержке института,&nbsp; - автоцистерны пожарные, причем как АЦ 5, АЦ 10, так и автоцистерны 11 и 12 тонн для тушения огня "с колес". Автомобили быстрого реагирования (АБР), автолестницы, автомобили порошкового тушения, автомобили аэродромного&nbsp;тушения, коленчатые подъемники, мобильные пункты управления&nbsp;и другая техника.
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
