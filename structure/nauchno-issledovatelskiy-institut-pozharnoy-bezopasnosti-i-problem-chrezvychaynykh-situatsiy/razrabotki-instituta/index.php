<h1>Пожарное оборудование</h1>
<p style="text-align: justify;">
	 Надежное и качественное пожарно-техническое вооружение и средства индивидуальной защиты спасателя-пожарного решают огромную роль в успешной ликвидации пожаров и чрезвычайных ситуаций. Защита органов дыхания, качественные пенообразователи, надежные рукава&nbsp;и стволы&nbsp; вместе с грамотными действиями спасателей&nbsp;- залог успеха.
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 Институт вот уже более полувека занимается разработкой средств защиты и пожарно-технического вооружения для служб спасения и пожарных. Среди разработок НИИ - рукава пожарные напорные диаметром,&nbsp;51,&nbsp;66 и 77 миллиметров. Ствол пожарный ручной универсальный (СПРУК-50/0,7)&nbsp; - «Викинг», аппарат дыхательный со сжатым воздухом «БДА»,&nbsp;&nbsp;а также различные пенообразоватили - фторсинтетические,&nbsp;синтетические, пленкообразующие. Подробнее читайте в характеристиках каждой разработки.
</p>
