<p style="text-align: justify;">
	Пожарно-техническая станция
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 15 июля 1969 года&nbsp;пожарно-испытательная станция преобразована в пожарно-техническую станцию. В штат пожарно-технической станции введены должности начальника, старшего инженера, старшего мастера, 3 инженера и 3 шофера. Возлагаемые на пожарно-техническую станцию задачи существенно не изменились, по сравнению с пожарно-испытательной станцией.<br>
