<h2>ИСТОРИЧЕСКАЯ СПРАВКА</h2>
<p>
	 Пожарно-испытательная станция
</p>
<p style="text-align: justify;">
	 История создания Научно-исследовательского института пожарной безопасности и проблем чрезвычайных ситуаций Министерства по чрезвычайным ситуациям Республики Беларусь начинается&nbsp;29&nbsp;сентября 1956 года&nbsp;с образования в г.Минске пожарно-испытательной станции.<br>
 <br>
</p>
<p align="center">
 <img width="318" alt="1.jpg" src="/upload/medialibrary/785/1yt45e3azlwbld46g1p73solf2y32ags.jpg" height="221" title="1.jpg"><br>
</p>
<p>
</p>
<p style="text-align: justify;">
	27 июня 1959 года&nbsp;пожарно-испытательная станция ОПО УВД исполкома Минского областного совета депутатов трудящихся переведена в непосредственное подчинение УПО МВД БССР. В штате пожарно-испытательной станции состояло 8 человек, в том числе начальник, инженер, 3 старших мастера и 3 водителя.<br>
</p>
<p>
</p>
<p>
</p>
<p align="center">
 <img width="318" alt="2.jpg" src="/upload/medialibrary/b06/cgczfh5yv3xm6i9bxpt3sscbfvj3akmg.jpg" height="227" title="2.jpg"><br>
</p>
<p>
	 На пожарно-испытательную станцию возлагался ряд научно-технических задач:<br>
</p>
<ul>
	<li>изучение явлений горения, повреждения строительных конструкций, особенностей распространения огня на пожаре;</li>
	<li>анализ боеспособности пожарной техники, пожарно-технического вооружения и снаряжения в обстановке пожара, работы специальных служб пожарной охраны;</li>
	<li>проведение технических экспертиз по выявлению причин пожаров;</li>
	<li>изучение условий применения и эффективности огнегасительных средств на пожарах;</li>
	<li>исследование вопросов эвакуации людей, а также причин несчастных случаев с людьми в условиях пожара;</li>
	<li>составление технической документации по каждому выезду на пожар;</li>
	<li>оказание помощи в работе местного гарнизона пожарной охраны в части производства необходимых испытаний, анализов и проверок средств пожаротушения, огнезащиты, ЛВЖ в пределах возможностей имеющейся испытательно-технической базы;</li>
	<li>участие в изучении пожарной опасности отдельных техпроцессов производств, а также решение других&nbsp; технических вопросов по заданиям УПО;</li>
	<li>оценка пожарной опасности горючих веществ и изделий, выпускаемых промышленностью и выдача по ним заключений на основании проведенных исследований и экспериментов;</li>
	<li>анализ состояния и работы средств водоснабжения и связи, проверка и испытание отдельных видов пожарной техники, а также стационарных систем тушения;</li>
	<li>проведение самостоятельных научно-исследовательских и испытательных работ в области пожарной профилактики, пожарной техники и др.;</li>
	<li>информирование пожарной охраны других областей, краев и республик по вопросам работы станции (через УПО МВД Республики);</li>
	<li>дача консультаций организациям и отдельным лицам по пожарно-техническим вопросам.</li>
</ul>
