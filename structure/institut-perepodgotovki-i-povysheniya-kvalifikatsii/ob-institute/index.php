<p style="text-align: justify;">
	Научно-исследовательский институт пожарной безопасности
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 В соответствии с постановлением Совета Министров Республики Беларусь от&nbsp;29 апреля 1998 г. № 673&nbsp;«О мерах по совершенствованию пожарной безопасности в Республике Беларусь» на базе Республиканского научно-практического центра пожарной безопасности создан Научно-исследовательский институт пожарной безопасности (НИИ ПБ) Главного управления военизированной пожарной службы Министерства внутренних дел Республики Беларусь. Указом Президента Республики Беларусь от&nbsp;11 сентября 1999 года №442&nbsp;«О реорганизации Министерства по чрезвычайным ситуациям Республики Беларусь» институт переподчинен Министерству по чрезвычайным ситуациям.<br>
 <br>
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 Научно-исследовательский институт пожарной безопасности и проблем чрезвычайных ситуаций
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 17 марта 2000 года&nbsp;в соответствии с указами Президента Республики Беларусь от&nbsp;11 сентября 1998 г. № 442&nbsp;«О реорганизации Министерства по чрезвычайным ситуациям Республики Беларусь» и от&nbsp;19 января 1999 г. № 35&nbsp;«Об утверждении Положения о Министерстве по чрезвычайным ситуациям Республики Беларусь», постановлением Совета Министров Республики Беларусь от&nbsp;29 апреля 1998 г. № 673&nbsp;«О мерах по совершенствованию системы пожарной безопасности в Республике Беларусь» НИИ ПБ преобразован в учреждение «Научно-исследовательский институт пожарной безопасности и проблем чрезвычайных ситуаций» Министерства по чрезвычайным ситуациям Республики Беларусь.<br>
 <br>
	 На сегодняшний день&nbsp;его основная деятельность – решение научно-технических проблем в области предупреждения и ликвидации чрезвычайных ситуаций. Институт является головным техническим научно-исследовательским учреждением по вопросам чрезвычайных ситуаций в Республике Беларусь, в т.ч. государственным испытательным центром страны. Принимает непосредственное участие в реализации единой государственной научно-технической политики в области предупреждения и ликвидации пожаров и других чрезвычайных ситуаций.
</p>
