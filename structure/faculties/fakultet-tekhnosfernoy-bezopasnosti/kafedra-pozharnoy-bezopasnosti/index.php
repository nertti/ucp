<p style="text-align: justify;">
	Кафедрой пожарной безопасности разработана межкафедральная дисциплина «Пожарная безопасность. Комплексный подход». Дисциплина включает направления кафедры пожарной безопасности, автоматических систем безопасности, а также организации надзорной и профилактической деятельности и направлена на совершенствование процессов оценки субъектов хозяйствования требованиям нормативных правовых актов, в том числе обязательных для соблюдения ТНПА, образующих систему противопожарного нормирования и стандартизации.
</p>
</span>
<p style="text-align: justify;">
	 Кафедра пожарной безопасности оказывает услуги экспертной деятельности в области обеспечения пожарной безопасности объектов на различных стадиях жизненного цикла зданий, этапах разработки проектной документации. Разработанные профессорско-преподавательским составом кафедры экспертные и проектные решения характеризуются значительным экономическим эффектом в области строительства.
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: center;">
 <b>&nbsp;Основные научные направления кафедры</b>
</p>
<p style="text-align: justify;">
	 Научно-исследовательская деятельность кафедры пожарной безопасности направлена на обеспечение и повышение уровня пожарной безопасности зданий и сооружений. Кафедра динамично развивает собственные кадры высшей квалификации. По результатам совместной деятельности профессорско-преподавательского состава на кафедре пожарной безопасности подготовлено 10 кандидатов технических наук и доктор технических наук.
</p>
<p>
	 В числе приоритетных направлений:
</p>
<p>
	 1)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; Огнестойкость и пожарная опасность материалов, строительных конструкций, зданий и сооружений – совершенствование методик моделирования поведения строительных конструкций при пожаре и совершенствование их конструктивной огнезащиты, совершенствование методик ограничения распространения пожара на соседние здания и сооружения.
</p>
<p>
	 2)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; Взрывозащита зданий и сооружений – совершенствование методик прогнозирования аварийных ситуаций с образованием избыточного давления взрыва и разработка эффективных легко-сбрасываемых конструкций.
</p>
<p>
	 3)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; Эвакуация людей при пожаре – совершенствование методик моделирования динамики опасных факторов пожара и движения людей к эвакуационным выходам.
</p>
<p>
	 4)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; Разработка тренажерных комплексов методического обеспечения практической подготовки работников ОПЧС – внедрение симуляционных технологий и деловых игр моделирования деятельности органов государственного пожарного надзора.
</p>
<p style="text-align: justify;">
	 Активно развивается научная школа в области предупреждения пожаров и взрывов. Выполнено более 30 научных проектов с проведением натурных огневых испытаний зданий, результаты которых внедрены в совершенствование нормативной базы и законодательства Республики Беларусь, а также в производство строительных организаций и в практическую деятельность проектных организаций.
</p>
