<p style="text-align: justify;">
	 Кафедра была создана в 1992 году в Высшем пожарно-техническом училище МВД Беларуси, а в 2016 году получила современное наименование. Кафедра готовит обучающихся по пожарно-профилактическому направлению обеспечения пожарной безопасности зданий и сооружений, строительных конструкций и инженерных систем на стадии проектирования и эксплуатации, а также осуществляет научное обеспечение пожарной и промышленной безопасности.<br>
	 На кафедре функционирует 3 учебных лаборатории:<br>
	 «Лаборатория безопасности инженерных систем»; «Лаборатория виртуального моделирования»; «Лаборатория по измерению аэродинамических характеристик систем вентиляции».
</p>
