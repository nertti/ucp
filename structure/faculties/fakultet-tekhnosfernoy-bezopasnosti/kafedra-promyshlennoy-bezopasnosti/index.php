</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 1)&nbsp;&nbsp;&nbsp;&nbsp;Разработка экспериментального макета тренажера по осуществлению надзорной деятельности в области пожарной и промышленной безопасности с использованием технологий компьютерного моделирования и виртуальной реальности.<br>
 <span style="color: #0f1115;">2)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</span>Разработка системы оперативного мониторинга пожарной опасности торфяных экосистем на основе синергии спутниковой климатологии и моделирования метеорологического дефицита влаги.<br>
 <span style="color: #0f1115;">3)&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</span>Исследование пожаровзрывоопасности дисперсионных аэрозолей биотехнологических производств<span style="color: #0f1115; background: white;">.</span>
</p>
<p style="text-align: justify;">
</p>
