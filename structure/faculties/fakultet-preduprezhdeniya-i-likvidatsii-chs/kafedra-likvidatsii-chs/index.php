</p>
<p>
</p>
<p style="text-align: justify;">
 <span style="background: white;">&nbsp; &nbsp;Научно-исследовательская деятельность кафедры ликвидации чрезвычайных ситуаций направлена на повышение эффективности действий подразделений МЧС Беларуси и совершенствование тактической подготовки специалистов. В числе приоритетных направлений:<br>
 </span><span style="background-color: white; color: #0f1115;">&nbsp; &nbsp;1.&nbsp;Разработка и исследование способов и тактических приёмов тушения пожаров ‒ с учётом современных рисков, новых материалов и технологий.<br>
 </span><span style="background-color: white; color: #0f1115;">&nbsp; &nbsp;2.&nbsp;Повышение эффективности тушения пожаров горючих и легковоспламеняющихся жидкостей ‒ оптимизация расхода огнетушащих веществ и тактических схем их подачи.<br>
 </span><span style="background-color: white; color: #0f1115;">&nbsp; &nbsp;3.&nbsp;Определение условий использования новых огнетушащих веществ и технических средств их подачи ‒ оценка применимости перспективных составов и оборудования в реальных условиях.<br>
 </span><span style="background-color: white; color: #0f1115;">&nbsp; &nbsp;4.&nbsp;Разработка и создание учебно-тренировочных программных комплексов для оценки действий первого руководителя тушения пожара (РТП) и начальника дежурной смены при проведении аварийно-спасательных работ ‒ внедрение симуляционных технологий и деловых игр с возможностью динамического изменения вводных.<br>
 </span><span style="background-color: white; color: #0f1115;">&nbsp; 5.&nbsp;Разработка аварийных карточек на транспортные средства с электроприводом ‒ обеспечение безопасности при ликвидации последствий ДТП с участием электротранспорта (риски поражения током, возгорания высоковольтных батарей).</span><span style="background-color: white; color: #0f1115;">&nbsp;</span>
</p>
