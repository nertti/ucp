<p align="center">
 <b>Основные научные направления кафедры</b>
</p>
<p>
</p>
<p style="text-align: justify;">
	 &nbsp; &nbsp;<span style="text-align: justify;">&nbsp; &nbsp; Научно-исследовательская деятельность кафедры безопасности жизнедеятельности направлена на поиск и внедрение инновационных технологий и методов обучения в образовательный процесс по направлениям гражданской обороны, предупреждения и ликвидации чрезвычайных ситуаций, исследование психологической готовности специалистов МЧС к профессиональной деятельности и информационно-коммуникативной компетентности работников сферы безопасности жизнедеятельности.</span>
</p>
