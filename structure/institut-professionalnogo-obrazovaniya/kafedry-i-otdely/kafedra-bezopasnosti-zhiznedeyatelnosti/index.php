</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 1) Исследование психологической готовности командиров гражданских формирований гражданской обороны к оказанию само- и взаимопомощи в чрезвычайных ситуациях<br>
	 2)&nbsp; Особенности психологической готовности к деятельности диспетчера центра оперативного управления МЧС Республики Беларусь.<br>
	 3)&nbsp; Формирование информационно-коммуникативной компетентности работников сферы безопасности жизнедеятельности
