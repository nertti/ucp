<p>В  1927 г.  было создано новое  структурное  подразделение НКВД БССР – Пожарная инспекция. В связи с бурным ростом экономики молодой советской республике нужны были квалифицированные специалисты для пожарной службы, способные грамотно организовать и проводить работу по предупреждению и тушению пожаров на объектах народного хозяйства, в городах и сельских населенных пунктах. Поэтому уже в конце 20-х гг. в связи с развитием народного хозяйства БССР встал вопрос о необходимости подготовки в республике кадров для пожарной охраны.</p>
