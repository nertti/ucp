<td style="text-align: justify;" colspan="3">В первые дни после освобождения столицы Советской Белоруссии от немецко-фашистских захватчиков в город вернулись и белорусские пожарные. Среди них был и Н.М. Шманай, выпускник Пожарно-технической школы г. Минска 1936 года. В первый же день после освобождения города он в числе первых принял участие в тушении горящих зданий столицы. После освобождения Минска от немецко-фашистских оккупантов в здании бывшей 2-й пожарной команды была размещена 6-я пожарная команда столицы, а в довоенной пристройке с 1  сентября 1944 г. возобновилась подготовка младшего начальствующего состава пожарной охраны для БССР, а также ряда областей РСФСР (Смоленской, Калининградской и др.). Комплектование школы осуществлял майор Козаченко Алексей Захарович, занимавший тогда должность начальника УПО МВД БССР. Приказом НКВД БССР № 0792 от 21 сентября 1944 г. начальником школы был назначен старший техник-лейтенант Алешкевич Андрей Данилович, который проработал в этой должности до 1948 года. Этим же приказом В.Л. Виноградов был назначен заместителем начальника школы по политической части.</td>
