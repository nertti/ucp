<td style="padding-left: 0px; text-align: justify;"><p style="text-align: center;"><strong><strong><strong><strong>FQ4  Учебное программное обеспечение «Тушение пожаров на промышленном объекте»</strong></strong></strong></strong></p>

<p><em><strong>Особенности:</strong></em><br />
В основе заложена трехмерная модель промышленного предприятия по изготовлению металлических деталей. В состав объекта входят: здание сборочного цеха; здание склада ЛКМ; здание склада готовой продукции; здание цеха механической обработки металла; здание котельной с компрессорной; открытое распределительное устройство; открытый склад металла. На всех этих объектах создано по несколько сценариев, мест возможного возникновения пожара. Обучаемый  управляет  силами и средствами при тушении пожара. Вид картинки – сверху, «с высоты птичьего полета».</p>

<p style="text-align: justify;"><em><strong>Назначение:</strong></em><br />
 Данный  программный комплекс предназначен для повышения эффективности учебного процесса подготовки начальствующего состава Министерства по чрезвычайным ситуациям Республики Беларусь, позволяет моделировать деятельность начальствующего состава по управлению пожарными аварийно-спасательными подразделениями при тушении пожаров на объектах хозяйствования.</p>

<em><strong>Конкурентные преимущества:</strong></em><br />
- Повышение качества и эффективности учебного процесса подготовки работников подразделений МЧС Республики Беларусь за счет внедрения инновационных образовательных технологий, реализованных в обучающей тренинговой программе.<br />
- Сетевая версия программы для группового обучения. <br />
<br />
<p style="text-align: justify;"><em><strong>Принцип работы:</strong></em><br />
– Программное обеспечение реализовано в виде “стратегии”, при этом действия происходят в реальном времени. Управление программой осуществляется от лица руководителей тушения пожара, который должен приданными ему силами и средствами потушить пожар в кратчайшие сроки, обеспечив минимальный ущерб от него. Управление действиями личного состава осуществляется путем операций с пожарными аварийно-спасательными автомобилями и пожарно-техническим вооружением.<br />
- В сетевой версии программы обучаемые могут отработать действия различных должностных лиц – руководителя тушения пожара, начальника штаба, начальника тыла, начальников боевых участков, диспетчера центра оперативного управления.<br />
 – Программа может функционировать в учебном и контрольном режимах. В учебном режиме пользователю предоставлена возможность использовать проектную документацию на объект, использовать справочную информацию, проводить требуемые расчеты при решении тактической задачи.</p>

<p style="text-align: justify;"><em><strong>Минимальные системные требования к ПК и программному обеспечению:</strong></em><br />
 ­        - процессор: Core 2 Duo с тактовой частотой 2500 МГц и выше;<br />
 ­        - ОЗУ: 2048МБ и более;<br />
 ­        - свободное место на дисковом пространстве: 2048 Мб;<br />
 ­        - видеокарта класса GeForce 8800 GT и выше;<br />
 ­        - разрешение монитора 1280?1024<br />
 ­        - поддержка манипулятора типа «мышь»;<br />
 ­        - сетевая карта: со скоростью соединения 10/100 мбит/с и выше.<br />
 ­        - операционная система Windows XP или Windows Vista</p>

<p style="text-align: justify; padding-left: 30px;"><em><strong>Программное обеспечение поставляется в виде базового комплекта, включающего:</strong></em><br />
 - программное обеспечение с необходимым количеством регистрационных электронных ключей;<br />
 - руководство пользователя;<br />
 - руководство администратора.</p>

