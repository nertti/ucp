 <b>The University of Civil Protection of the Ministry for Emergency Situations of the Republic of Belarus</b>
</p>
<p style="background: white;">
	 &nbsp;
</p>
<p style="background: white;">
	 The University of Civil Protection of the Ministry for Emergency Situations of the Republic of Belarus carries out the activities in training experts in the field of emergency response to natural and man-made disasters, industrial safety and civil defense.
</p>
<p style="background: white;">
	 The University is one of the leading educational establishments of higher education. The University provides:
</p>
<p style="background: white;">
	 1.&nbsp;&nbsp;&nbsp;&nbsp; The first stage of higher education (bachelor degree);
</p>
<p style="background: white;">
	 2.&nbsp;&nbsp;&nbsp;&nbsp; The second stage of higher education (master degree);
</p>
<p style="background: white;">
	 3.&nbsp;&nbsp;&nbsp;&nbsp; Postgraduate education;
</p>
<p style="background: white;">
	 4.&nbsp;&nbsp;&nbsp;&nbsp; Retraining on the basis of higher education;
</p>
<p style="background: white;">
	 5.&nbsp;&nbsp;&nbsp;&nbsp; Qualification upgrading (short-term courses).
</p>
<p style="background: white;">
	 Qualification upgrading of foreign specialists has been conducted since 2003. The University has a modern training field for practical exercises. Its 34 training fields and grounds make it possible to imitate and simulate a wide range of different emergencies.
</p>
<p style="background: white;">
	 At present more than 4 600 specialists from 49 countries have undergone training at the University.
</p>
<p style="background: white;">
	 The University has close cooperation in the framework of educational projects implementation with such international organizations as: International Civil Defense Organization (ICDO), Organization for the Prohibition of Chemical Weapons (OPCW), Interstate Aviation Committee (IAC), European Commission (EC), International Atomic Energy Agency (IAEA) and others.
</p>
<p style="background: white;">
	 There is a wide range of training courses developed by our teaching staff. If necessary the existing programs can be amended or new programs can be developed to satisfy the needs of a customer.
</p>
<p style="background: white;">
	 The training groups are formed by 5-16 specialists. Tuition fee for training is calculated individually for each customer and may include the following services as the parties agree: meeting at the National Airport “Minsk”, seeing off after graduation, three meals a day at our canteen; special uniform and footwear for practical training at the training field; printed handouts for the training program; stationery set; access to the Internet; the use of sports facilities; medical help at the university medical centre; cultural and sightseeing activities on weekend; group photo with the leadership.
</p>
<p style="background: white;">
	 Cost for training includes: for one-week course – not more than US $ 650 dollars for one person; for the two-week course – not more than US $ 1250 for a person (including all the services mentioned above).
</p>
<p style="background: white;">
	 In case the University hostel rooms are available the trainees may live at the hostel. The cost of accommodation for a person is as follows: US $ 18 a night (single room) or US $ 15 a night (double room).
</p>
<p style="background: white;">
	 Accommodation can be also arranged in Minsk and other Belarusian cities and towns. In this case the customer pays all the expenses and the University will provide transfer from a hotel to the place of study.
</p>
<p style="background: white;">
	 The training can be organized:
</p>
<p style="background: white;">
	 -&nbsp;&nbsp;in the Russian language, with translation into English (an interpreter will be provided by the University;
</p>
<p style="background: white;">
	 -&nbsp; in the national languages of trainees &nbsp;(an interpreter can arrive together with the group or be hired on a fee basis).
</p>
