<p>
	 The international activity of the State establishment "University of Civil Protection of the Ministry for Emergency Situations of the Republic of Belarus" is carried out in accordance with the provisions of the Strategy of International Cooperation of the Ministry for Emergency Situations of the Republic of Belarus, corresponding to the basic principles of the foreign policy of the state, confirmed by the Law of the Republic of Belarus of 14.11.2005 "On Approval of the Main Directions of Internal and Foreign Policy of the Republic of Belarus".
</p>
<p>
	 The purpose of the University's international activities is to strengthen the status of the establishment as the leading specialized educational establishment, expand the educational space, intensify scientific research, and develop intercultural interaction.
</p>
<p>
	 The University is a basic organization for training personnel in the field of prevention and elimination of emergency situations of the Commonwealth of Independent States, as well as actively cooperates with the International Civil Defense Organization, the Organization for the Prohibition of Chemical Weapons, the International Atomic Energy Agency, the Interstate Aviation Committee, the International Civil Aviation Organization.
</p>
<p>
	 The educational establishment actively participates in the activities of international organizations aimed at providing highly professional multilevel training:
</p>
<p>
	 - since 2010 together with the International Civil Defense Organization (ICDO) the University provides training of specialists in the field of prevention and elimination of emergency situations and civil protection, in 2022 the University was included in the list of affiliated members of the organization by the decision of the General Assembly of the International Civil Defense Organization;
</p>
<p>
	 - since 2013, the University and its branches have been implementing training programs for specialists in protection against chemical weapons with the Organization for the Prohibition of Chemical Weapons (OPCW);
</p>
<p>
	 - In 2013, the University was certified by the Interstate Aviation Committee as an educational establishment that trains specialists to conduct emergency rescue and firefighting operations on aircraft and civil aviation facilities in accordance with the Standards and Recommended Practices of the International Civil Aviation Organization, training specialists in the organization of aviation search and rescue operations, as well as emergency rescue training for flight and cabin crew members. In 2022, the certificate was once again renewed.
</p>
<p>
	 The University cooperates in the development of modern public safety technologies and training in collaboration with the Institute of Public Safety of Tsinghua University and BEIJING GLOBAL SAFETY TECHNOLOGY (GSafety) of the People's Republic of China.
</p>
<p>
	 The partnership relations connect the University of Civil Protection and the Academy of State Fire Fighting Service of EMERCOM of Russia, Civil Defense Academy EMERCOM of Russia, Saint Petersburg University of State Fire Service of EMERCOM of Russia, Ivanovo Fire and Rescue Academy of EMERCOM of Russia, Ural Institute of State Fire Fighting Service EMERCOM of Russia, Siberian Fire Rescue Academy EMERCOM of Russia, Academy of Civil Protection named after M. Gabdullin of the Ministry of Emergency Situations of the Republic of Kazakhstan, Academy of the Ministry for Emergency Situations of the Republic of Azerbaijan, Civil Protection Institute of the Ministry for Emergency Situations of the Republic of Uzbekistan, Academy of the Ministry for Emergency Situations of the Republic of Uzbekistan, Academy of the Ministry of Internal Affairs of the Republic of Tajikistan, University of Fire Prevention and Fighting of the Ministry of Public Security of the Socialist Republic of Vietnam and other educational establishments.
</p>
<p>
	 The University has been successfully training foreign specialists since 2003. Annually the ranks of students, master’s course listeners and postgraduate are enlarged by about 100 representatives of the CIS countries and foreign countries.
</p>
<p>
	 On the basis of the International Rescue-firefighters Training Center - IRTcentre (a branch of the University "Institute of Retraining and Professional Development") the implementation of advanced training programs, retraining, as well as short-term courses in the field of firefighting and rescue operations in conditions as close as possible to real emergencies is carried out.
</p>
<p>
	 More than 7100 foreign specialists from 71 countries have been trained at the University and its branches in recent years.
</p>
