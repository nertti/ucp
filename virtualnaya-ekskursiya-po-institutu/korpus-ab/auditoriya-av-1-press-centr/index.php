<p style="text-align: justify;">Вашему вниманию представлен учебный пресс-центр.</p>
<p style="text-align: justify;">Сейчас как никогда важно наличие эффективного взаимодействия со средствами массовой&nbsp; информации. Для обеспечения подготовки в данном направлении создан учебный пресс-центр, зонированный на три части, в каждой из которых отрабатываются определенные навыки:&nbsp;&nbsp;</p>
<p style="text-align: justify;">В первой зоне проводится тренировка сообщения с места чрезвычайной ситуации. На баннерах показана обстановка, сложившаяся в ходе наиболее характерных для Беларуси ЧС, задача обучаемого правильно подготовить и представить перед камерой сообщение для СМИ о произошедшем.</p>
<p style="text-align: justify;">Во второй зоне проводится подготовка к проведению «Пресс-конференций». Зона оснащена двухсторонним&nbsp; баннером&nbsp; с логотипами «МЧС» и «КИИ МЧС». Здесь происходит подготовка, направленная на формирование умений отвечать на поставленные вопросы, в нужном контексте с минимальным интервалом времени на обдумывание ответа.&nbsp;</p>
<p style="text-align: justify;">В третьей зоне проводится отработка действий по ведению переговоров, здесь же проводится анализ выступлений обучающихся, снятых на видео в 1 и 2 зонах.</p>

