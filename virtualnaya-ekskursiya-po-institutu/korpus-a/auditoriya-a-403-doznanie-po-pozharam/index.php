<p style="text-align: justify;">-&nbsp;получать навыки работы со специальным инструментом;</p>
<p style="text-align: justify;">-&nbsp;грамотно изымать, упаковывать и сохранять вещественные доказательства с мест пожара;</p>
<p style="text-align: justify;">-&nbsp;оформлять необходимые процессуальные документы.</p>
