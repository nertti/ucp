<p style="text-align: justify;">Вашему вниманию представлена аудитория дознания по пожарам.</p>
<p style="text-align: justify;">В соответствие со статьей 37 Уголовно-процессуального кодекса, должностные лица органов ГПН уполномочены осуществлять дознание по уголовным делам о пожарах и нарушении противопожарных правил.&nbsp; Одна из основных задач в дознании в делах о пожарах правильная фиксация обстановки на месте пожара. Для подготовки специалистов в данном направлении создана данная аудитория.</p>
