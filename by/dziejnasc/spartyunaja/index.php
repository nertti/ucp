<p style="text-align: justify;">
	 Адным з асноўных напрамкаў дзейнасці Дзяржаўнай установы адукацыі “Універсітэт грамадзянскай абароны Міністэрства па надзвычайных сітуацыях Рэспублікі Беларусь” з'яўляецца павышэнне ўзроўню фізічнай падрыхтаванасці курсантаў, студэнтаў і слухачоў Універсітэта для паспяховага выканання службовых задач. Для гэтага ва Універсітэце арганізавана работа 11 спартыўных груп па відах спорту, у якіх займаюцца практычна ўсе навучэнцы. У рамках круглагадовай спартакіяды Універсітэта праводзяцца спаборніцтвы па 15 відах спорту, у тым ліку і відах спорту прыкладной накіраванасці.
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 Вялікая ўвага ва Універсітэце надаецца матэрыяльна-тэхнічнаму перааснашчэнню спартыўных збудаванняў. За апошнія гады створаны і рэканструяваны залы агульнафізічнай падрыхтоўкі і ігравых відаў спорту. У стадыі рэканструкцыі знаходзіцца спецыялізаваны стадыён, які адказвае сучасным міжнародным патрабаванням для правядзення спаборніцтваў па пажарна-выратавальным і іншых відах спорту.
</p>
<p style="text-align: justify;">
</p>
<p style="text-align: justify;">
	 Асобная ўвага ва Універсітэце надаецца падрыхтоўцы спартсменаў-выратавальнікаў. У цяперашні час касцяк зборнай каманды Рэспублікі Беларусь па пажарна-выратавальным спорце складаюць выпускнікі Універсітэта, якія пачыналі сваю спартыўную кар'еру са школьнай парты і пад кіраўніцтвам вопытных выкладчыкаў і трэнераў дасягнулі высокіх спартыўных вынікаў. На сённяшні дзень ва Універсітэце падрыхтаваны 4 майстры спорту Рэспублікі Беларусь міжнароднага класа, 36 майстроў спорту, больш за 100 кандыдатаў у майстры спорту Рэспублікі Беларусь. У сценах Універсітэта выхаваны рэкардсмены, чэмпіёны і прызёры чэмпіянатаў свету і Еўропы па пажарна-выратавальным спорце.
