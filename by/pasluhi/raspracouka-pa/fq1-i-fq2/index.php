			 - фиксация выявленных нарушений может осуществляться с помощью встроенного блокнота или автоматически с использованием контекстного меню. По результатам проведения проверки автоматически представляется отчет, в котором указывается процент выявленных нарушений по каждому слою. Данную информацию можно детализировать для отдельного здания. Для оформления необходимых по результатам проверки документов формируется полный перечень выявленных обучаемым нарушений.
